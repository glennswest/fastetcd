//! etcd's v3 JSON gateway (fastetcd#28): `POST /v3/...` on the client
//! port, beside `/health`, so HTTP tools (a console, `curl`) can use the
//! etcd API without a gRPC client.
//!
//! It is etcd's own surface, as etcd v3.6 serves it (grpc-gateway v2,
//! `server/embed/serve.go`), so recipes and tools written against etcd
//! work unchanged:
//!
//! - Routes are the `google.api.http` annotations of etcd's `rpc.proto`
//!   (see [`router`]). Every call is a `POST` whose body is the request
//!   message as JSON; an empty body is the default request.
//! - JSON is protojson with `UseProtoNames` and no default fields: proto
//!   field names (`raft_term`, `dbSize`, `ID`), 64-bit integers as
//!   strings, bytes (keys and values) base64, enums by name. Input takes
//!   either field spelling, and unknown fields are ignored. The serde
//!   impls are generated by pbjson (`fastetcd-proto`).
//! - An error is the HTTP status grpc-gateway maps its gRPC code to,
//!   with body `{"code":N,"message":"…"}`.
//! - A streamed response (`/v3/maintenance/snapshot`) is one JSON object
//!   per line: `{"result":{…}}`, or `{"error":{"code":N,"message":"…"}}`.
//!
//! Nothing here is new behaviour: each call is decoded, passed through
//! the same [`AuthInterceptor`] as gRPC (the token comes from the
//! `Authorization` header, as etcd's gateway forwards it; a TLS client
//! certificate's CN identifies the caller exactly as over gRPC), and
//! handed to the same service implementation, whose own permission
//! checks then apply. Calls are counted in `grpc_server_*_total` under
//! the method they call, as etcd's are (its gateway dials the gRPC
//! server).

